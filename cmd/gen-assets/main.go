func genTeapotOBJ(path string) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	fmt.Fprintln(f, "# Utah Teapot — Newell (1975), public domain")
	fmt.Fprintln(f, "# Tessellated from Bezier patches by gen-assets")
	fmt.Fprintln(f, "mtllib teapot.mtl")
	fmt.Fprintln(f, "usemtl teapot")

	N := tessN
	stride := N + 1
	vertsPerPatch := stride * stride

	// Write all vertices, UVs, and normals for all patches first, then faces.
	// This avoids interleaving OBJ sections.

	// Pass 1: positions (v), UVs (vt), normals (vn).
	for p := 0; p < 32; p++ {
		var ctrl [4][4]vec3
		for i := 0; i < 4; i++ {
			for j := 0; j < 4; j++ {
				idx := teapotPatches[p][i*4+j] - 1 // 0-indexed
				raw := teapotPts[idx]
				// Convert Z-up (Newell) → Y-up: output (x, z, y).
				ctrl[i][j] = vec3{raw[0], raw[2], raw[1]}
			}
		}

		for vi := 0; vi <= N; vi++ {
			u := float64(vi) / float64(N)
			for vj := 0; vj <= N; vj++ {
				v := float64(vj) / float64(N)
				pos, du, dv := evalPatch(ctrl, u, v)
				// Flip winding: after Y↔Z swap the handedness reversed,
				// so negate the normal (cross dv×du instead of du×dv).
				nrm := normalize(cross(dv, du))
				fmt.Fprintf(f, "v %f %f %f\n", pos[0], pos[1], pos[2])
				fmt.Fprintf(f, "vt %f %f\n", u, v)
				fmt.Fprintf(f, "vn %f %f %f\n", nrm[0], nrm[1], nrm[2])
			}
		}
	}

	// Pass 2: faces (triangulated quads).
	for p := 0; p < 32; p++ {
		base := p*vertsPerPatch + 1 // OBJ is 1-indexed
		for vi := 0; vi < N; vi++ {
			for vj := 0; vj < N; vj++ {
				a := base + vi*stride + vj
				b := base + vi*stride + (vj + 1)
				c := base + (vi+1)*stride + vj
				d := base + (vi+1)*stride + (vj + 1)
				// CCW triangles viewed from outside (after normal flip above).
				fmt.Fprintf(f, "f %d/%d/%d %d/%d/%d %d/%d/%d\n", a, a, a, d, d, d, b, b, b)
				fmt.Fprintf(f, "f %d/%d/%d %d/%d/%d %d/%d/%d\n", a, a, a, c, c, c, d, d, d)
			}
		}
	}
	return nil
}

// genCheckerPNG writes a checkerboard RGBA PNG with warm teapot colors.
func genCheckerPNG(path string, size, tileSize int) error {
	img := image.NewRGBA(image.Rect(0, 0, size, size))
	for y := 0; y < size; y++ {
		for x := 0; x < size; x++ {
			if ((x/tileSize)+(y/tileSize))%2 == 0 {
				img.SetRGBA(x, y, color.RGBA{R: 200, G: 150, B: 100, A: 255}) // warm tan
			} else {
				img.SetRGBA(x, y, color.RGBA{R: 120, G: 80, B: 50, A: 255}) // dark brown
			}
		}
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, img)
}
