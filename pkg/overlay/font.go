package overlay

// GlyphWidth and GlyphHeight define the pixel dimensions of each bitmap glyph.
// Each glyph is stored as GlyphHeight uint8 rows; bit GlyphWidth-1 is the
// leftmost (most-significant) pixel.
const (
	GlyphWidth  = 8
	GlyphHeight = 8
)

// Glyph is a fixed-size bitmap for one character: GlyphHeight rows of
// GlyphWidth pixels packed as bits (MSB = left column).
type Glyph [GlyphHeight]uint8

// GlyphFor returns the bitmap glyph for the given ASCII byte.
// Unmapped bytes return a blank glyph.
func GlyphFor(c byte) Glyph {
	if g, ok := glyphs[c]; ok {
		return g
	}
	return Glyph{}
}

