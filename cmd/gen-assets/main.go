type vec3 [3]float64

func add(a, b vec3) vec3 { return vec3{a[0] + b[0], a[1] + b[1], a[2] + b[2]} }
func scale(a vec3, s float64) vec3 { return vec3{a[0] * s, a[1] * s, a[2] * s} }
func cross(a, b vec3) vec3 {
	return vec3{
		a[1]*b[2] - a[2]*b[1],
		a[2]*b[0] - a[0]*b[2],
		a[0]*b[1] - a[1]*b[0],
	}
}
func normalize(a vec3) vec3 {
	l := math.Sqrt(a[0]*a[0] + a[1]*a[1] + a[2]*a[2])
	if l < 1e-10 {
		return vec3{0, 1, 0}
	}
	return vec3{a[0] / l, a[1] / l, a[2] / l}
}

// bern evaluates the i-th degree-3 Bernstein basis polynomial at t.
func bern(i int, t float64) float64 {
	u := 1.0 - t
	switch i {
	case 0:
		return u * u * u
	case 1:
		return 3 * t * u * u
	case 2:
		return 3 * t * t * u
	case 3:
		return t * t * t
	}
	return 0
}

// dbern evaluates the derivative of the i-th degree-3 Bernstein basis polynomial at t.
func dbern(i int, t float64) float64 {
	u := 1.0 - t
	switch i {
	case 0:
		return -3 * u * u
	case 1:
		return 3 * u * (u - 2*t)
	case 2:
		return 3 * t * (2*u - t)
	case 3:
		return 3 * t * t
	}
	return 0
}

// evalPatch evaluates a bicubic Bézier patch at (u,v).
// ctrl[i][j] is the control point at row i, col j.
// Returns position, ∂/∂u tangent, ∂/∂v tangent.
func evalPatch(ctrl [4][4]vec3, u, v float64) (pos, du, dv vec3) {
	for i := 0; i < 4; i++ {
		bi := bern(i, u)
		dbi := dbern(i, u)
		for j := 0; j < 4; j++ {
			bj := bern(j, v)
			dbj := dbern(j, v)
			p := ctrl[i][j]
			pos = add(pos, scale(p, bi*bj))
			du = add(du, scale(p, dbi*bj))
			dv = add(dv, scale(p, bi*dbj))
		}
	}
	return
}

